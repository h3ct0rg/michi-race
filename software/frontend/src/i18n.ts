const DICTS: Record<Lang, Record<Key, string>> = { es, en };
const KEY = 'michi.lang';

const stored = (): Lang | null => {
  try {
    const v = localStorage.getItem(KEY);
    return v === 'es' || v === 'en' ? v : null;
  } catch {
    return null;
  }
};

let lang: Lang = stored() ?? 'es';
const listeners = new Set<(l: Lang) => void>();

export const getLang = () => lang;

export function t(key: Key, params?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? es[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Traduce un mensaje de error del servidor (si hay traducción). */
export const tServer = (msg: string) => (lang === 'en' ? (SERVER_ERRORS[msg] ?? msg) : msg);

/** Aplica las traducciones a los elementos marcados con data-i18n*. */
export function applyI18n(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n as Key)));
  root.querySelectorAll<HTMLInputElement>('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria as Key)));
  document.documentElement.lang = lang;
}

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* modo privado */
  }
  applyI18n();
  listeners.forEach((l) => l(next));
}

export function onLangChange(fn: (l: Lang) => void) {
  listeners.add(fn);
}
